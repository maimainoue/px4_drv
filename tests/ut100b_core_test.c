#define EV_MAX 2048

struct ev {
	u8 type, req;
	u16 value, index, len;
};

struct mock {
	struct ev *ev;
	int n;
	int fail_at;		/* この番号 (1 から) の転送が -EIO で失敗する (0 は無効) */
	bool bad_info;		/* GetCusInfo の VID/PID が 3275:7020 でない */
	u8 asie_version;	/* ASIE5606 のレジスタ 9 */
	u8 card_state;		/* ASIE5606 のレジスタ 4 */
	u8 cndat[3];
	u8 r80, rb0;		/* 復調器のレジスタ 0x80、0xb0 */
};

static struct mock *new_mock(void)
{
	struct mock *m = calloc(1, sizeof(*m));

	m->ev = calloc(EV_MAX, sizeof(struct ev));
	m->asie_version = 0x06;
	m->card_state = 0x01;
	return m;
}

static void free_mock(struct mock *m)
{
	free(m->ev);
	free(m);
}

static int mock_control(void *priv, u8 rt, u8 req, u16 value, u16 index, void *buf, u16 len)
{
	struct mock *m = priv;
	u8 *b = buf;
	struct ev *e;

	if (m->n >= EV_MAX)
		abort();
	e = &m->ev[m->n++];
	e->type = rt;
	e->req = req;
	e->value = value;
	e->index = index;
	e->len = len;
	if (m->fail_at && m->n == m->fail_at)
		return -EIO;
	memset(b, 0, len);
	b[0] = 1;	/* 状態 */
	if (req == 0x0c) {
		if (!m->bad_info) {
			b[3] = 0x32; b[4] = 0x75; b[5] = 0x70; b[6] = 0x20;
		}
	} else if (req == 0x02 && len >= 2) {
		u8 addr = (u8)value, reg = (u8)(value >> 8);

		b[1] = 0;
		if (addr == 0x4a && reg == 0x09)
			b[1] = m->asie_version;
		else if (addr == 0x4a && reg == 0x04)
			b[1] = m->card_state;
		else if (addr == 0x20 && reg >= 0x8b && reg <= 0x8d)
			b[1] = m->cndat[reg - 0x8b];
		else if (addr == 0x20 && reg == 0x80)
			b[1] = m->r80;
		else if (addr == 0x20 && reg == 0xb0)
			b[1] = m->rb0;
	}
	return len;
}

