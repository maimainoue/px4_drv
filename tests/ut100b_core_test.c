static int count_req(const struct mock *m, u8 req)
{
	int i, n = 0;

	for (i = 0; i < m->n; i++)
		if (m->ev[i].req == req)
			n++;
	return n;
}

/* 要求 0x03 (レジスター書き込み) の、I2C アドレス addr のレジスター reg への書き込みの回数 (reg が負なら全部) */
static int count_reg_writes(const struct mock *m, u8 addr, int reg)
{
	int i, n = 0;

	for (i = 0; i < m->n; i++)
		if (m->ev[i].req == 0x03 && (u8)m->ev[i].value == addr && (reg < 0 || (u8)(m->ev[i].value >> 8) == reg))
			n++;
	return n;
}

static int find_req(const struct mock *m, u8 req, int from)
{
	int i;

	for (i = from; i < m->n; i++)
		if (m->ev[i].req == req)
			return i;
	return -1;
}

static void test_des_vectors(void)
{
	static struct ut100b_cipher c;
	u8 out[188];

	ut100b_cipher_init(&c);
	ut100b_cipher_decrypt_packet(&c, out, vec0_src);
	CHECK(memcmp(out, vec0_dst, 188) == 0);
	ut100b_cipher_decrypt_packet(&c, out, vec1_src);
	CHECK(memcmp(out, vec1_dst, 188) == 0);
	ut100b_cipher_decrypt_packet(&c, out, vec2_src);
	CHECK(memcmp(out, vec2_dst, 188) == 0);
	/* dst と src が同じでもよい */
	memcpy(out, vec1_src, 188);
	ut100b_cipher_decrypt_packet(&c, out, out);
	CHECK(memcmp(out, vec1_dst, 188) == 0);
	/* ヘッダーの 4 バイトはそのまま */
	CHECK(memcmp(vec0_src, vec0_dst, 4) == 0);
}

/*
 * 先頭が 0x47 でも、188 バイト後が 0x47 でない候補は、同期位置として確定しない。
 * 余分な 0x47 を 1 バイト置いて 3 パケットを続けた入力で、一括で渡した場合と、188 バイトの位置で分けて渡した場合の
 * どちらも、正しい位置の 3 パケットを出力する。
 */
static void test_aligner_false_sync(void)
{
	static struct ut100b_aligner a, b;
	static u8 stream[1 + 188 * 3], expect[188 * 3], out[188 * 4];
	size_t i, n;

	ut100b_aligner_init(&a);
	for (i = 0; i < 3; i++) {
		u8 *p = stream + 1 + 188 * i;

		memset(p, (int)(0x11 * (i + 1)), 188);
		p[0] = 0x47;
		p[187] = 0x00;
		ut100b_cipher_decrypt_packet(&a.cipher, expect + 188 * i, p);
	}
	stream[0] = 0x47;

	/* 一括 (a は、期待値を作るときに初期化済み。resyncs などを数え直すため、もう一度初期化する) */
	ut100b_aligner_init(&a);
	a.stale = 0;
	n = ut100b_aligner_feed(&a, stream, sizeof(stream), out);
	CHECK(n == 188 * 3);
	CHECK(memcmp(out, expect, sizeof(expect)) == 0);
	CHECK(a.resyncs == 1 && a.skipped == 1);

	/* 188 バイトの位置で分ける。候補の確認に使う位置が入力の外にあるため、1 回目は確定せず、何も出力しない。 */
	ut100b_aligner_init(&b);
	b.stale = 0;
	n = ut100b_aligner_feed(&b, stream, 189, out);
	CHECK(n == 0);
	n = ut100b_aligner_feed(&b, stream + 189, sizeof(stream) - 189, out);
	CHECK(n == 188 * 3);
	CHECK(memcmp(out, expect, sizeof(expect)) == 0);

	/* 先頭に余分な 0x00 と 0x47 を置いた入力を 1 バイトずつ渡しても、同じ結果になる */
	ut100b_aligner_init(&b);
	b.stale = 0;
	{
		static u8 all_out[188 * 4];
		size_t total = 0;

		for (i = 0; i < sizeof(stream); i++)
			total += ut100b_aligner_feed(&b, stream + i, 1, all_out + total);
		CHECK(total == 188 * 2 || total == 188 * 3);
		CHECK(memcmp(all_out, expect, total) == 0);
	}
}

static void test_aligner(void)
{
	static struct ut100b_aligner a;
	u8 in[188 * 3 + 3 + 64], out[188 * 4];
	static u8 junk[UT100B_STALE_DISCARD_BYTES];
	size_t n;

	ut100b_aligner_init(&a);
	/* 受け始めの UT100B_STALE_DISCARD_BYTES は、中身にかかわらず捨てる (2 回に分けても合計で数える) */
	memset(junk, 0x47, sizeof(junk));
	CHECK(ut100b_aligner_feed(&a, junk, 100, out) == 0);
	CHECK(a.stale == UT100B_STALE_DISCARD_BYTES - 100);
	CHECK(ut100b_aligner_feed(&a, junk, UT100B_STALE_DISCARD_BYTES - 100, out) == 0);
	CHECK(a.stale == 0 && a.rest_len == 0);

	/*
	 * 先頭に 3 バイトの余りがあるとき、区切りを探し直して、3 つのパケットを復号する。2 回に分けて渡す。
	 * 区切りの確認には先頭、188、376 バイト後の 3 か所が要る。1 回目の入力では、3 か所目がまだ届かないため、
	 * 候補の位置から後を持ち越して、何も出力しない。
	 */
	in[0] = 0x00; in[1] = 0x01; in[2] = 0x02;
	memcpy(in + 3, vec0_src, 188);
	memcpy(in + 3 + 188, vec1_src, 188);
	memcpy(in + 3 + 188 * 2, vec2_src, 188);
	n = ut100b_aligner_feed(&a, in, 3 + 188 + 50, out);
	CHECK(n == 0);
	CHECK(a.resyncs == 1 && a.skipped == 3);
	CHECK(a.rest_len == 188 + 50 && !a.synced);
	n = ut100b_aligner_feed(&a, in + 3 + 188 + 50, 188 * 2 - 50, out);
	CHECK(n == 188 * 3);
	CHECK(memcmp(out, vec0_dst, 188) == 0 && memcmp(out + 188, vec1_dst, 188) == 0 &&
	      memcmp(out + 188 * 2, vec2_dst, 188) == 0);
	CHECK(a.rest_len == 0 && a.resyncs == 1 && a.synced);
	CHECK(ut100b_aligner_out_capacity(&a, 188 * 3 + 10) == 188 * 3);

	/* 188 バイト未満は、次の入力まで持つ */
	CHECK(ut100b_aligner_feed(&a, vec0_src, 100, out) == 0 && a.rest_len == 100);
	CHECK(ut100b_aligner_feed(&a, vec0_src + 100, 88, out) == 188);
	CHECK(memcmp(out, vec0_dst, 188) == 0);
	test_aligner_false_sync();
}

static void test_board_open(void)
{
	struct mock *m = new_mock();
	struct hz2w_bridge b;
	int i, first_gpio, last_asie_zero = -1, ts_mode = -1;

	hz2w_bridge_init(&b, &ops, m);
	CHECK(ut100b_board_open(&b) == 0);
	CHECK(m->ev[0].req == 0x0c);
	/* 復調器の初期化表 94 個と、0x1c の書き直し 1 個 */
	CHECK(count_reg_writes(m, 0x20, -1) == 94 + 1);
	/* ASIE5606 (0x4a) への書き込み: TS の暗号の方式 1 個と、0x10..0x1f の 0 が 16 個 */
	CHECK(count_reg_writes(m, 0x4a, -1) == 1 + 16);
	CHECK(count_reg_writes(m, 0x4a, 0x05) == 1);
	for (i = 0; i < m->n; i++) {
		if (m->ev[i].req == 0x03 && (u8)m->ev[i].value == 0x4a && (u8)(m->ev[i].value >> 8) == 0x05)
			ts_mode = m->ev[i].index;
		if (m->ev[i].req == 0x03 && (u8)m->ev[i].value == 0x4a && (u8)(m->ev[i].value >> 8) == 0x1f)
			last_asie_zero = i;
	}
	CHECK(ts_mode == 0x80);	/* DES */
	CHECK(last_asie_zero == m->n - 1);
	/* I2C の送り (0x0e) は、リセットの 1 バイトと、チューナーの初期化表 19 個 */
	CHECK(count_req(m, 0x0e) == 1 + 19);
	/* 先頭の GPIO は 0xfb/0x07 (値 0x07、mask 0xfb) */
	first_gpio = find_req(m, 0x08, 0);
	CHECK(first_gpio >= 0 && m->ev[first_gpio].value == (0xfb << 8 | 0x07));
	free_mock(m);

	/* 基板の識別が 3275:7020 でないときは、何も初期化しない */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	m->bad_info = true;
	CHECK(ut100b_board_open(&b) == -ENODEV);
	CHECK(m->n == 1);
	free_mock(m);

	/* DES でない版の ASIE5606 は拒否する */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	m->asie_version = 0x04;
	CHECK(ut100b_board_open(&b) == -ENODEV);
	CHECK(count_reg_writes(m, 0x4a, 0x05) == 0);
	free_mock(m);

	/* どの転送が失敗しても、成功として扱わない */
	for (i = 1; i <= 60; i++) {
		m = new_mock();
		hz2w_bridge_init(&b, &ops, m);
		m->fail_at = i;
		CHECK(ut100b_board_open(&b) != 0);
		free_mock(m);
	}
}

static void test_tune_and_close(void)
{
	struct mock *m = new_mock();
	struct hz2w_bridge b;
	u32 cndat = 0;
	int i, found_lo = -1, found_hi = -1, start, filter_last;

	hz2w_bridge_init(&b, &ops, m);
	CHECK(ut100b_tune(&b, 557143) == 0);
	/* 周波数: 557 MHz x 64 = 35648 = 0x8b40。チューナーのレジスター 0x14 (下位) と 0x15 (上位) */
	for (i = 0; i + 1 < m->n; i++) {
		if (m->ev[i].req == 0x0d && m->ev[i].index == (u16)((0x14 << 8) | 0xc0) &&
		    m->ev[i + 1].req == 0x0d && m->ev[i + 1].value == (u16)((0x40 << 8) | 3))
			found_lo = i;
		if (m->ev[i].req == 0x0d && m->ev[i].index == (u16)((0x15 << 8) | 0xc0) &&
		    m->ev[i + 1].req == 0x0d && m->ev[i + 1].value == (u16)((0x8b << 8) | 3))
			found_hi = i;
	}
	CHECK(found_lo >= 0 && found_hi > found_lo);
	/* 選局では TS を流し始めない (TS フィルターの設定と受信の開始は、ut100b_stream_start) */
	CHECK(count_req(m, 0x05) == 0 && count_req(m, 0x09) == 0 && count_req(m, 0x06) == 0);
	free_mock(m);

	/* TS の開始: 0x09 (フィルターのリセット)、0x04 (読み出し)、0x05 (書き込み 3 回)、最後に 0x06 (受信の開始) */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	CHECK(ut100b_stream_start(&b) == 0);
	start = find_req(m, 0x06, 0);
	filter_last = -1;
	for (i = 0; i < m->n; i++)
		if (m->ev[i].req == 0x05)
			filter_last = i;
	CHECK(m->ev[0].req == 0x09);
	CHECK(start >= 0 && filter_last >= 0 && start > filter_last);
	CHECK(count_req(m, 0x05) == 3);
	CHECK(count_req(m, 0x09) == 1);
	CHECK(m->ev[m->n - 1].req == 0x06);
	free_mock(m);
	/* 途中の転送が失敗したら、受信を始めない */
	for (i = 1; i <= 5; i++) {
		m = new_mock();
		hz2w_bridge_init(&b, &ops, m);
		m->fail_at = i;
		CHECK(ut100b_stream_start(&b) != 0);
		CHECK(count_req(m, 0x06) == 0);
		free_mock(m);
	}
	/* 受信の停止: 0x07 とフィルターのリセット (0x09) */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	CHECK(ut100b_stream_stop(&b) == 0);
	CHECK(m->n == 2 && m->ev[0].req == 0x07 && m->ev[1].req == 0x09);
	free_mock(m);

	/* 別の周波数 (UHF 13ch の中心 473.143 MHz は 473 MHz へ丸める) */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	CHECK(ut100b_tune(&b, 473143) == 0);
	found_lo = -1;
	for (i = 0; i + 1 < m->n; i++) {
		if (m->ev[i].req == 0x0d && m->ev[i].index == (u16)((0x14 << 8) | 0xc0) &&
		    m->ev[i + 1].req == 0x0d && m->ev[i + 1].value == (u16)((((473 * 64) & 0xff) << 8) | 3))
			found_lo = i;
	}
	CHECK(found_lo >= 0);
	free_mock(m);

	/* 転送の失敗は、選局の失敗として返す (受信を始めない) */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	m->fail_at = 5;
	CHECK(ut100b_tune(&b, 557143) != 0);
	CHECK(count_req(m, 0x06) == 0);
	free_mock(m);

	/* C/N の生の値 */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	m->cndat[0] = 0x01; m->cndat[1] = 0x23; m->cndat[2] = 0x45;
	CHECK(ut100b_read_cndat(&b, &cndat) == 0 && cndat == 0x012345);
	free_mock(m);

	/* ロックの判定 */
	{
		bool locked = true;

		m = new_mock();
		hz2w_bridge_init(&b, &ops, m);
		m->r80 = 0x00; m->rb0 = 0x08;
		CHECK(ut100b_is_locked(&b, &locked) == 0 && locked);
		m->rb0 = 0x07;
		CHECK(ut100b_is_locked(&b, &locked) == 0 && !locked);
		m->rb0 = 0x0f; m->r80 = 0x08;	/* bit 3 が立っている間はロックしていない (0xb0 は読まない) */
		m->n = 0;
		CHECK(ut100b_is_locked(&b, &locked) == 0 && !locked && m->n == 1);
		m->r80 = 0x20;
		CHECK(ut100b_is_locked(&b, &locked) == 0 && !locked);
		m->fail_at = m->n + 1;
		CHECK(ut100b_is_locked(&b, &locked) != 0 && !locked);
		free_mock(m);
	}

	/* 閉じる手順: 受信の停止、フィルターのリセット、カード側のレジスターを 0、チューナーの電源を切る */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	ut100b_board_close(&b);
	CHECK(m->ev[0].req == 0x07);
	CHECK(count_reg_writes(m, 0x4a, 0x80) == 1 && count_reg_writes(m, 0x4a, 0x04) == 1 && count_reg_writes(m, 0x4a, 0x00) == 1);
	CHECK(m->ev[m->n - 1].req == 0x08 && m->ev[m->n - 1].value == (0x08 << 8 | 0x08));
	free_mock(m);
}

/* 受信中にカードを使っても、ASIE5606 の TS の設定 (レジスター 5、リセットのパルス) を壊さない */
static void test_card_keeps_ts_settings(void)
{
	struct mock *m = new_mock();
	struct hz2w_bridge b;
	struct hz2w_card c;

	hz2w_bridge_init(&b, &ops, m);
	ut100b_card_init(&c, &b);
	CHECK(c.keep_ic_state);
	m->card_state = 0x00;	/* カードなし: 電源投入の前の段階で止まる */
	hz2w_card_set_timeout(&c, 1000);
	CHECK(hz2w_card_reset(&c) == -ENXIO);
	CHECK(count_req(m, 0x23) == 0 && count_req(m, 0x21) == 0);
	CHECK(count_reg_writes(m, 0x4a, 0x05) == 0);
	/* 前のセッションの途中のやり取りを止める準備の命令 (レジスター 0 に 0x80) を出す */
	{
		int i, prepare = 0;

		for (i = 0; i < m->n; i++)
			if (m->ev[i].req == 0x03 && (u8)m->ev[i].value == 0x4a && (u8)(m->ev[i].value >> 8) == 0x00 && m->ev[i].index == 0x80)
				prepare++;
		CHECK(prepare == 1);
	}
	free_mock(m);

	/* HZ2W (従来) は、リセットのパルスと要求 0x23、0x21、レジスター 5 への書き込みを行う */
	m = new_mock();
	hz2w_bridge_init(&b, &ops, m);
	hz2w_card_init(&c, &b);
	CHECK(!c.keep_ic_state);
	m->card_state = 0x00;
	hz2w_card_set_timeout(&c, 1000);
	CHECK(hz2w_card_reset(&c) == -ENXIO);
	CHECK(count_req(m, 0x23) == 1 && count_req(m, 0x21) == 1);
	CHECK(count_reg_writes(m, 0x4a, 0x05) == 1);
	/* HZ2W は準備の命令 (0x80) を出さない */
	{
		int i, prepare = 0;

		for (i = 0; i < m->n; i++)
			if (m->ev[i].req == 0x03 && (u8)m->ev[i].value == 0x4a && (u8)(m->ev[i].value >> 8) == 0x00 && m->ev[i].index == 0x80)
				prepare++;
		CHECK(prepare == 0);
	}
	free_mock(m);
}

